const pad = (data: number[]): number[] => {
  const out = data.slice(0, PACKET_LEN)
  while (out.length < PACKET_LEN) out.push(0x00)
  return out
}

// Matches the C#/Python checksum: acc starts at 128, then acc += byte + 2 per byte.
const checksum = (textBytes: Buffer): number => {
  let acc = 128
  for (const b of textBytes) acc += b + 2
  return acc % 256
}

export const buildTextPacket = (text: string): number[] => {
  const chars = [...text]
  const clipped = chars.length > MAX_TEXT_CHARS ? chars.slice(0, MAX_TEXT_CHARS).join('') : text
  const textBytes = Buffer.from(clipped, 'utf8')
  const textLen = textBytes.length
  const totalLen = 1 + textLen + 1 // textLen(1) + text(N) + checksum(1)
  const pkt = [
    ...TEXT_HEADER,
    totalLen & 0xff,
    (totalLen >> 8) & 0xff,
    textLen & 0xff,
    ...textBytes,
    checksum(textBytes),
  ]
  return pad(pkt)
}

export const buildLayoutPacket = (layout: HaloPixelLayout): number[] => pad([...LAYOUTS[layout]])

export const buildUIModelPacket = (model: HaloPixelUIModel): number[] => pad([...UI_MODELS[model]])

// Rough display width: CJK-ish code points count as 2, everything else as 1.
export const displayWidth = (text: string): number => {
  let width = 0
  for (const c of text) width += (c.codePointAt(0) ?? 0) > 0x2e80 ? 2 : 1
  return width
}
