// HID protocol for the "花再 Halo PixelBar" device, ported from HaloPixelToolBox.
// Every packet is a fixed 64 bytes. The first byte (0x2E) is itself the HID
// Report ID, so it is written as-is without any extra leading prefix.

export const PACKET_LEN = 64
export const DEVICE_NAME = '花再 Halo PixelBar'
export const DEVICE_USAGE_PAGE = 0xff14
export const MAX_TEXT_CHARS = 50

const TEXT_HEADER = [0x2e, 0xaa, 0xec, 0xe8, 0x00]

export type HaloPixelLayout = 'center' | 'left' | 'right' | 'stretch' | 'scrollLeft' | 'scrollRight'

export const LAYOUTS: Record<HaloPixelLayout, number[]> = {
  center: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x00, 0x01, 0xff, 0xfd, 0x00],
  left: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x00, 0x00, 0xff, 0xfc, 0x00],
  right: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x00, 0x02, 0xff, 0xfe, 0x00],
  stretch: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x00, 0x03, 0xff, 0xff, 0x00],
  scrollLeft: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x01, 0x00, 0xff, 0xfd, 0x00],
  scrollRight: [0x2e, 0xaa, 0xec, 0xef, 0x00, 0x09, 0x01, 0xf0, 0xb4, 0xc8, 0x00, 0x02, 0x01, 0x01, 0xff, 0xfe, 0x00],
}

